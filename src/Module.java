class Module {
    String moduleName;
    char labGroup;

    public String getModuleName() {
        return moduleName;
    }

    public char getLabGroup() {
        return labGroup;
    }

    public void setModuleName(String moduleName) {
        this.moduleName = moduleName;
    }

    public void setLabGroup(char labGroup) {
        this.labGroup = labGroup;
    }
}